def build_neko_love_style(neko_number: int | str | None, neko_name: str = "猫", tag: str = "") -> str:
    """猫タイプに合わせた恋愛傾向の短文を返す。既存プロフィールは変更しない。"""
    try:
        number = int(neko_number or 1)
    except Exception:
        number = 1
    number = min(60, max(1, number))
    lead = f"{neko_name}は、恋でも「{tag or '自分らしさ'}」が魅力に出やすい猫。"
    return lead + _LOVE_STYLE_TAILS[(number - 1) % len(_LOVE_STYLE_TAILS)]


def _date_key(now: Any = None) -> str:
    if isinstance(now, datetime):
        return now.date().isoformat()
    if isinstance(now, date):
        return now.isoformat()
    return datetime.now().date().isoformat()


def build_neko_love_iching(
    birthdate: str | None,
    neko_name: str = "猫",
    now: Any = None,
) -> Dict[str, Any]:
    """生年月日と猫タイプから、長く読める恋愛イーチンを安定して1卦選ぶ。"""
    seed = f"neko-love-iching-v2|{birthdate or ''}|{neko_name}"
    digest = hashlib.sha256(seed.encode("utf-8")).digest()
    index = int.from_bytes(digest[:8], "big") % 64
    name, theme, love, action = ICHING_LOVE_64[index]
    number = index + 1
    return {
        "number": number,
        "name": name,
        "theme": theme,
        "love": love,
        "action": action,
        "label": f"第{number}卦 {name} - {theme}",
        "cat_line": f"{neko_name}のひげが恋愛の性質として選んだ卦は「{name}」にゃ。",
    }
