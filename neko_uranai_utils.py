def get_neko_profile(eto_number: int | str | None) -> Dict[str, Any]:
    """60干支番号から猫占いプロフィールを返す。"""
    try:
        number = int(eto_number or 0)
    except Exception:
        number = 0
    if not (1 <= number <= 60):
        number = 1
    idx = number - 1
    name = NEKO60[idx]
    return {
        "number": number,
        "name": name,
        "tag": NEKO_TAGS[idx],
        "description": NEKO_DESCRIPTIONS[idx],
        "image_path": f"static/neko60/{number:02d}.png",
    }


def _clean_iching_text(text: Any, max_chars: int = 170) -> str:
    s = str(text or "").replace("\r\n", "\n").replace("\r", "\n")
    s = re.sub(r"\s+", " ", s).strip()
    s = re.sub(r"^(易|イーチン|I Ching|おみくじ|御籤)[:：\s]*", "", s, flags=re.I)
    if len(s) > max_chars:
        s = s[:max_chars].rstrip("、。,. ") + "。"
    return s


