def get_neko_profile(eto_number: int | str | None) -> Dict[str, Any]:
    """日柱干支番号から猫占いプロフィールを返す。"""
    try:
        number = int(eto_number or 0)
    except Exception:
        number = 0
    if not (1 <= number <= 60):
        number = 1
    idx = number - 1
    name = NEKO60[idx]
    return {
        "number": number,
        "name": name,
        "tag": NEKO_TAGS[idx],
        "image_path": f"static/neko60/{number:02d}.png",
    }


def _clean_iching_text(text: Any, max_chars: int = 180) -> str:
    s = str(text or "").replace("\r\n", "\n").replace("\r", "\n")
    s = re.sub(r"\s+", " ", s).strip()
    # 見出しが混じる場合の軽い掃除
    s = re.sub(r"^(易|イーチン|I Ching|おみくじ|御籤)[:：\s]*", "", s, flags=re.I)
    if len(s) > max_chars:
        s = s[:max_chars].rstrip("、。,. ") + "。"
    return s


def build_neko_omikuji(iching_result: Any, neko_name: str = "猫") -> str:
    """既存のイーチン結果を土台に、猫っぽい口調の御籤文へ整える。

    OpenAI APIを追加で呼ばないため、生成コスト・待ち時間・失敗点を増やしません。
    """
    base = _clean_iching_text(iching_result)
    if not base:
        base = "今日は足元の気配をよく見て、急がず間合いを取ると流れが整います。"

    return (
        f"{neko_name}からのお告げにゃ。{base}\n"
        "今はあわてて爪を立てるより、しっぽをゆらして様子を見る時にゃん。"
        "気になることほど一拍おいて、近づく・離れるの距離感を選ぶと福が寄ってくるにゃ。"
        "小さな違和感はひげのセンサー。無視せず、でも怖がりすぎず、今日の一歩を軽く踏み出すにゃん。"
    )
